// Resolve a single free-text token to its partial tag vector, or null.
export function lexiconVector(token) {
  // Own-property only: "constructor", "toString" and friends are query words,
  // not entries (lib/brain/kb.js records what walking the chain cost).
  const key = String(token || '').trim().toLowerCase();
  const entry = Object.hasOwn(LEXICON, key) ? LEXICON[key] : undefined;
  return entry ? { ...entry } : null;
}
